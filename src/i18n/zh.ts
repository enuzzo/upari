/** The callers pass billions and millions already formatted ("8.2", "655"): back to a number, to count in 亿 and 万. */
const value = (s: string) => Number(s.replace(/,/g, ''));
const decimals = (s: string) => (s.includes('.') ? s.split('.')[1].length : 0);
/** "8.2" billion → "82 亿" */
const yi = (b: string) => `${num(value(b) * 10, Math.max(0, decimals(b) - 1))} 亿`;
/** "655" million → "6.55 亿", "87" million → "8,700 万" */
const wan = (m: string) => { const v = value(m) * 1e6; return v >= 1e8 ? `${num(v / 1e8, 2)} 亿` : `${num(v / 1e4)} 万`; };
/** Thousands ("412") counted in 万: "41.2". */
const wanK = (k: string) => num(value(k) / 10, value(k) % 10 ? 1 : 0);

