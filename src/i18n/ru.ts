/** Russian plurals: 1 пожар, 2 пожара, 5 пожаров. Takes a number or a string already formatted
 *  for ru-RU ("1 234", "2,5"); a fraction takes the "few" form (2,5 года). */
const PLURAL = new Intl.PluralRules('ru');
const pl = (n: number | string, one: string, few: string, many: string) => {
  const v = typeof n === 'number' ? n : Number(n.replace(/[^\d,]/g, '').replace(',', '.'));
  const c = PLURAL.select(v);
  return c === 'one' ? one : c === 'few' || c === 'other' ? few : many;
};

