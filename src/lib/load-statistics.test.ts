import {afterEach,expect,it,vi} from 'vitest';
import {readFileSync} from 'node:fs';
import {loadIncludedStatistics} from './load-statistics';
import {annualPair,validateStatisticsBundle} from './statistics';
import {journeysFor} from './journeys';
afterEach(()=>vi.unstubAllGlobals());
it('loads the real EU27 snapshot with exact observations, legal policy and no invented global coverage',async()=>{
 vi.stubGlobal('fetch',async(path:string)=>new Response(readFileSync('public'+path,'utf8')));
 const bundle=await loadIncludedStatistics(new AbortController().signal),{data}=bundle;
 expect(data.indicators).toHaveLength(9);
 expect(Object.keys(data.values.renewables)).toHaveLength(27);
 expect(annualPair(data,'renewables','ITA',2004).left).toBe(6.316);
 expect(annualPair(data,'renewables','ITA',2024).left).toBe(19.385);
 expect(annualPair(data,'renewables','USA',2024).left).toBeNull();
 expect(annualPair(data,'renewables','ITA',2003).left).toBeNull();
 expect(annualPair(data,'renewables','ITA',2025).left).toBeNull();
 expect(data.indicators.find(m=>m.id==='renewables')?.license).toBe('Eurostat-Reuse');
 expect(journeysFor(data).map(r=>r.id)).toEqual(['energy-europe','longer-lives','protection']);
 expect(journeysFor({...data,flows:undefined}).map(r=>r.id)).not.toContain('protection');
 expect(journeysFor({...data,flows:{...data.flows!,origins:['AFG','UKR','SYR']}}).map(r=>r.id)).not.toContain('protection');
 expect(JSON.stringify(validateStatisticsBundle(JSON.parse(JSON.stringify(bundle))))).toBe(JSON.stringify(bundle));
});
